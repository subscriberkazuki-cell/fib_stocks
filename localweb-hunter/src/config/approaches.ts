// 業種ごとの営業アプローチ。
//
// 「HPを作りませんか」は、どの業種に言っても同じように弱い。
// 相手が困っているのは Web ではなく商売の方なので、
// **その業種の商売で実際に起きている取りこぼし**から入る必要がある。
//
// 例：
//   飲食店に「SEO対策を」→ 刺さらない
//   飲食店に「食べログ経由だと手数料がかかりますよね」→ 話が始まる
//
// この表は営業の現場で更新していく前提。刺さった切り口を書き足していくこと。

