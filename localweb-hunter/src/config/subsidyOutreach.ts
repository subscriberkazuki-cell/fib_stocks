// 補助金サポート事業の営業設計。
//
// ============================================================
// 心理設計：どうすれば「申請してみたい」になるか
// ============================================================
//
// 補助金を使わない理由の1位は「知らない」ではなく **「面倒そう」** である。
// つまり潰すべきは情報不足ではなく、**着手のハードル**。
// この順番で組み立てる。
//
// ① 損失として提示する（得ではなく）
//    「50万円もらえます」より「使える制度を使っていない状態です」の方が強い。
//    損失回避は同額の利得のおよそ2倍の重みで効く（Kahneman-Tversky）。
//
// ② 金額を具体的に出す
//    「補助金が使えます」は他人事。「御社なら最大50万円、実質負担は3分の1」で自分事になる。
//
// ③ 「難しそう」を先に潰す
//    ここが最大の障壁。「商工会議所が無料で手伝ってくれます」と最初に言う。
//    自分のサービスを売る前に、無料の選択肢を教える。
//
// ④ 利益相反を自分から開示する
//    「私はHP制作もしているので、そこは利害関係があります」と先に言う。
//    隠して後から発覚するより、自分から言う方が信用は上がる。
//    これは誠実さのシグナルとして極めて強く働く。
//
// ⑤ 本物の締切で動かす
//    偽の緊急性は使わない。**様式4の締切が申請締切より11日早い**という事実がある。
//    本物の締切なので、そのまま使えるし、伝えないと相手が損をする。
//
// ⑥ 小さな第一歩にする
//    「申請しましょう」ではなく「商工会議所に電話してみてください」。
//    無料で、予約するだけ。ここを越えれば次は軽くなる。
//
// ============================================================
// HP制作への流れ
// ============================================================
//
// 補助金の話から入ると、HP制作に自然に着地する。順番が効いている。
//
//   1. 無料診断 → 信頼を得る（何も売っていない）
//   2. 商工会議所を案内 → 無料の選択肢を先に教える（利害がないことを示す）
//   3. 「ウェブ費用だけでは申請できません。他に何を申請しますか？」
//      → **この質問への答えとしてHP制作が出てくる**
//   4. 見積書を出す（申請書に添付が必要）
//   5. 採択 → 交付決定 → HP制作を受注
//   6. 月額へ
//
// 売り込みではなく「申請を成立させるために必要なもの」としてHPが出てくるので、
// 抵抗が生じにくい。

