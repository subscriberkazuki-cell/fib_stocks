// 先出し提案の進め方。
//
// ■ なぜこの順番なのか
//
// 写真を店主からもらう方針にすると、単純に考えれば
//   「接触 → 許可を取る → 写真をもらう → 制作 → 見せる」
// という順になる。しかしこれは最初の接触で相手に「許可」と「写真を集める作業」を
// 同時に求めることになり、そこで止まる。写真集めは店主にとって面倒な作業で、
// まだ何も見ていない相手のためにやる理由がない。
//
// そこで順番を入れ替える。
//   「写真なしで作る → 見せる → 写真をもらう」
//
// 写真なしで一度完成させてから見せると、
//   ・相手は「何のために写真が要るのか」を目で理解している
//   ・自分の店のサイトが既に存在している状態から始まる（保有効果）
//   ・写真を出すことが、断る側ではなく進める側の小さな一歩になる
// という状態を作れる。写真の提供が、承諾のハードルではなく
// 「もっと良くするための参加」に変わる。

