// 業種別のデザイン指針。
//
// ここが「店のイメージに合ったサイト」の中身。
// AIに「いい感じのサイトを作って」と頼むと、業種に関係なく
// 同じ顔のSaaSランディングページ（グラデーションのヒーロー＋3カラムの特徴カード＋
// 架空の推薦文）が出てくる。柏の整体院にそれを出しても刺さらない。
//
// 色・書体・構成・写真の扱いを業種ごとに指定して、その既定値を潰す。

export type PhotoNeed = 'required' | 'helpful' | 'optional';

export interface SiteDesign {
  /** CATEGORY_PRESETS の label と対応 */
  category: string;

  /** そのサイトが達成すべきこと。最初に据えると出力がぶれない */
  objective: string;

  /** 想定する来訪者と、その人が知りたいこと */
  visitor: string;

  /** 色。HEXまで指定しないとAIは無難な青にしてくる */
  palette: { bg: string; ink: string; accent: string; sub: string; note: string };

  /** 書体の方向。日本語Webフォントは指定しないと游ゴシック止まりになる */
  typography: string;

  /** 全体の印象を一言で。形容詞の羅列ではなく、具体的な参照で書く */
  mood: string;

  /** セクションの順序。上から下への導線そのもの */
  sections: string[];

  /** 主要な行動 */
  primaryCta: string;

  /** 写真がどれだけ必要か */
  photoNeed: PhotoNeed;

  /**
   * 実写真でなければならないもの。
   * ここにフリー素材を使うと、来店した客が「写真と違う」となる。
   * 景表法上も優良誤認になり得る。
   */
  realPhotoOnly: string[];

  /** フリー素材で代替してよいもの */
  stockPhotoOk: string[];

  /** 写真が無い段階で、代わりに何で見せるか */
  withoutPhotos: string;

  /** この業種で書いてはいけない表現 */
  forbidden: string[];

  /** この業種のサイトで効く、細かいが差がつく要素 */
  details: string[];
}

