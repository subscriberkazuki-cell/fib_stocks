// ============================================================
// 経済性の判断
//
// ここを間違えると「サポート料を払ったのに補助金の方が少ない」という事故が起きる。
// ============================================================

/**
 * サポートを勧めてよいかの判断。
 *
 * 判定は提案するプランによって変わる。
 *   1ページ ¥98,000  → 補助 約¥65,000。サポート料¥49,800を引くと手取りは¥15,000程度。
 *                      **これでは勧める意味がない。**
 *   標準サイト ¥198,000 → 補助 約¥132,000。サポート料を引いても¥82,000残るので成立する。
 *
 * なお **ウェブ関連費だけでは申請できない** ので、実際の申請額はここに他の経費が乗る。
 * つまりこの数字は下限であって、「これでも足りていれば安全に勧められる」という見方をする。
 * 足りない場合は、他の投資を確認してからでないと提案してはいけない。
 *
 * どちらにせよ「他に何か投資の予定はありますか」と聞くことが、
 * 営業としても店舗の利益としても正しい。
 */
export function isSupportWorthwhile(expectedSubsidy: number, supportFee: number): boolean {
  // サポート料を引いても、店舗に十分な手取りが残るか
  const netGain = expectedSubsidy - supportFee;
  return netGain >= supportFee; // 手取りがサポート料の倍以上あること
}

/** サポートを勧めてよい最低ライン（補助金額） */
export function minimumSubsidyForSupport(supportFee: number): number {
  return supportFee * 2;
}
