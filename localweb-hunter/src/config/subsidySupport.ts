//
// したがってこの事業は **「書かない」ことを設計の中心に置く。**
// 店主が自分で書くのを助ける形にし、書類作成が必要になったら行政書士に引き継ぐ。
//
// なお「書かない」制約は、サービスとしてはむしろ良い方向に働く。
// 自分で書いた計画は理解が深く実行されるし、審査でも自分の言葉の方が通りやすい。
// 丸投げしたい客は行政書士に行くので、手のかかる客を自然に弾ける。

